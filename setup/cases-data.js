const TONE_LABEL = {
  neutral: 'เรียบเฉย (ปกติ)', anxious: 'กังวล / เครียด', hurried: 'รีบร้อน',
  tired: 'อ่อนเพลีย / ไม่ค่อยมีแรง', irritable: 'หงุดหงิด / รำคาญ',
};

function assembleSecretInfo(f) {
  const lines = [`โทนอารมณ์: ${TONE_LABEL[f.tone] || TONE_LABEL.neutral}`];
  const push = (title, arr) => {
    if (!arr.length) return;
    lines.push('', title);
    arr.forEach(x => lines.push(`- ${x}`));
  };
  const split = (t) => (t || '').split('\n').map(l => l.trim()).filter(Boolean);
  push('[หมวด 1: อาการหลัก — ตอบได้ทันทีถ้าถาม]', split(f.mainSymptoms));
  push('[หมวด 2: รายละเอียดอาการ — ต้องถามเฉพาะ]', [
    f.symptomCharacter && `ลักษณะอาการ: ${f.symptomCharacter}`,
    f.duration         && `ระยะเวลา: ${f.duration}`,
    f.severity         && `ความรุนแรง: ${f.severity}`,
    f.associated       && `อาการร่วม: ${f.associated}`,
    f.factors          && `ปัจจัยที่ทำให้แย่ลง/ดีขึ้น: ${f.factors}`,
  ].filter(Boolean));
  push('[หมวด 3: ประวัติการรักษา — ต้องถาม]', [
    f.prevTreatment && `ยาที่ลองใช้แล้ว: ${f.prevTreatment}`,
    f.pastHistory   && `ประวัติเคยเป็น: ${f.pastHistory}`,
  ].filter(Boolean));
  push('[หมวด 4: ความปลอดภัย — CRITICAL ต้องถาม]', [
    f.underlyingDisease && `โรคประจำตัว: ${f.underlyingDisease}`,
    f.regularMeds       && `ยาประจำ: ${f.regularMeds}`,
    f.drugAllergy       && `ประวัติแพ้ยา: ${f.drugAllergy}`,
  ].filter(Boolean));
  push('[หมวด 5: ข้อมูลเพิ่มเติม]', split(f.additional));
  push('[หมวด 6: Red Flags — ถ้าถูกถาม]', split(f.redFlags));
  return lines.join('\n').trim();
}

function makeCase(c) {
  return { name: 'auto', isActive: false, ...c, secretInfo: assembleSecretInfo(c.secretInfoFields) };
}

