// combining marks ไทย: ไม้หันอากาศ, สระบน/ล่าง, วรรณยุกต์, ทัณฑฆาต, ยามักการ
const MARKS = '\u0E31\u0E34-\u0E3A\u0E47-\u0E4E';
// ช่องว่างทุกชนิดที่ PDF แทรก — non-breaking space กับ zero-width พบบ่อยในไฟล์ไทย
const WS = '[ \\t\u00A0\u2000-\u200B\uFEFF]';

const RE_DUP_MARK = new RegExp(`([${MARKS}])\\1+`, 'g');
const RE_SARA_AM  = new RegExp(`([\u0E01-\u0E2E][${MARKS}]?)${WS}+า(?![${MARKS}])`, 'g');
const RE_SPLIT_AM = new RegExp(`([ก-ฮ][${MARKS}]?)${WS}+ำ`, 'g');
const RE_FFFD_AM  = new RegExp(`([\u0E01-\u0E2E][${MARKS}]?)\uFFFD\\s*า(?![${MARKS}])`, 'g');

function repairThai(text) {
  if (!text) return '';
  let t = String(text);

  // 1) mark ตัวเดียวกันซ้ำติดกัน -> เหลือตัวเดียว
  //    ปลอดภัย: ภาษาไทยไม่มีการเขียน mark ตัวเดียวกันซ้ำติดกัน
  //    (ต่างตัวติดกันได้ เช่น ตั้ง = ต + ั + ้ จึงต้องใช้ backreference ไม่ใช่ character class)
  t = t.replace(RE_DUP_MARK, '$1');

  // 2) "ำ" ที่แตกเป็น พยัญชนะ + ช่องว่าง + "า"
  //    ปลอดภัย: า ไม่ขึ้นต้นคำในภาษาไทย ช่องว่างหน้า า จึงเป็นบั๊กเสมอ
  //
  //    ⚠️ lookahead ต้องเป็น [MARKS] เท่านั้น — ห้ามใช้ [\u0E30-\u0E4E]
  //    ช่วงนั้นครอบสระนำ เ แ โ ใ ไ (0E40-0E44) ซึ่งขึ้นต้นคำถัดไปเป็นปกติ
  //    ทำให้ "ค าแนะนำ" ไม่ถูกซ่อม (เคยพลาดมาแล้ว ครึ่งหนึ่งของเคสจริงหลุด)
  t = t.replace(RE_SARA_AM, '$1ำ');

  // 3) "ำ" ที่เป็น ำ อยู่แล้ว แต่ถูกช่องว่างแยกจากพยัญชนะ ("ค ำน ำ" -> "คำนำ")
  //    ปลอดภัยด้วยเหตุผลเดียวกับข้อ 2: ำ ขึ้นต้นคำในภาษาไทยไม่ได้
  //    พบน้อย (3 ครั้งในคลัง เทียบกับ 648 ของข้อ 2) แต่เป็นกฎเดียวกันจึงเก็บให้ครบ
  t = t.replace(RE_SPLIT_AM, '$1ำ');

  // 4) "ำ" ที่ถูกแทนด้วย U+FFFD ("จ\uFFFDาเป็น" -> "จำเป็น")
  t = t.replace(RE_FFFD_AM, '$1ำ');

  // 5) U+FFFD ที่เหลือ -> ทิ้ง ดีกว่าปล่อยให้ปนเข้า embedding
  t = t.replace(/\uFFFD/g, '');

  return t;
}

module.exports = { repairThai, MARKS, WS };
