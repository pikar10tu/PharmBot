// เดิมมี escape helper ก๊อปกัน 5 ตัว (_esc / _escA / _escM / _escH / _escS)
// และ "ไม่เหมือนกัน" — 3 ตัวไม่ escape เครื่องหมายคำพูด ทั้งที่ admin.js
// เอาไปใส่ใน value="..." ของ <input> (ชื่อยาที่มี " จะทำฟอร์มพัง)
// รวมเหลือ 2 ตัวตามพฤติกรรมที่ต่างกันจริงๆ คือ "ขึ้นบรรทัดใหม่หรือไม่"

// ใช้กับข้อความทั่วไป และทุกครั้งที่ยัดค่าลงใน attribute
function escapeHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// ใช้กับข้อความยาวที่ต้องคง \n ไว้ให้เห็นเป็นบรรทัดใหม่
// (บทสนทนาผู้ป่วย, feedback จาก AI) — ห้ามใช้ใน attribute
function escapeHtmlBr(str) {
  return escapeHtml(str).replace(/\n/g, '<br>');
}
